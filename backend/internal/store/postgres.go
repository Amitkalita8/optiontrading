// Tables in foreign-key order (parents first), for copying data.
var Tables = []string{"approaches", "watchlists", "watchlist_items", "campaigns", "positions", "trade_log",
	"notifications", "users", "profiles", "user_state", "password_resets"}

const pgDriverName = "pgx-rebind"

var registerOnce sync.Once

func register() { sql.Register(pgDriverName, rebindDriver{stdlib.GetDefaultDriver()}) }

// OpenPostgres connects to url (postgres://user:pass@host:5432/db?sslmode=disable)
// and migrates the schema.
func OpenPostgres(url string) (*sql.DB, error) {
	registerOnce.Do(register)
	db, err := sql.Open(pgDriverName, url)
	if err != nil {
		return nil, fmt.Errorf("store: open postgres: %w", err)
	}
	db.SetMaxOpenConns(20)
	db.SetMaxIdleConns(5)
	if err := db.Ping(); err != nil {
		db.Close()
		return nil, fmt.Errorf("store: connect to postgres: %w", err)
	}
	if err := migratePostgres(db); err != nil {
		db.Close()
		return nil, err
	}
	return db, nil
}

// OpenConfigured uses Postgres when databaseURL is set, else the SQLite file.
func OpenConfigured(databaseURL, sqlitePath string) (*sql.DB, error) {
	if strings.TrimSpace(databaseURL) != "" {
		return OpenPostgres(databaseURL)
	}
	return Open(sqlitePath)
}

func migratePostgres(db *sql.DB) error {
	if _, err := db.Exec(`CREATE TABLE IF NOT EXISTS schema_version (version INTEGER NOT NULL)`); err != nil {
		return fmt.Errorf("store: schema_version: %w", err)
	}
	var version int
	err := db.QueryRow(`SELECT version FROM schema_version`).Scan(&version)
	if errors.Is(err, sql.ErrNoRows) {
		if _, err := db.Exec(`INSERT INTO schema_version (version) VALUES (0)`); err != nil {
			return err
		}
	} else if err != nil {
		return fmt.Errorf("store: read schema version: %w", err)
	}
	for i := version; i < len(pgMigrations); i++ {
		tx, err := db.Begin()
		if err != nil {
			return err
		}
		if _, err := tx.Exec(pgMigrations[i]); err != nil {
			tx.Rollback()
			return fmt.Errorf("store: postgres migration %d: %w", i+1, err)
		}
		if _, err := tx.Exec(`UPDATE schema_version SET version = ?`, i+1); err != nil {
			tx.Rollback()
			return err
		}
		if err := tx.Commit(); err != nil {
			return err
		}
	}
	return nil
}

// IsPostgres reports whether db was opened with OpenPostgres.
func IsPostgres(db *sql.DB) bool {
	_, ok := db.Driver().(rebindDriver)
	return ok
}

// EngineName is "PostgreSQL" or "SQLite".
func EngineName(db *sql.DB) string {
	if IsPostgres(db) {
		return "PostgreSQL"
	}
	return "SQLite"
}

// IsUniqueViolation reports a duplicate-key error on either database.
func IsUniqueViolation(err error) bool {
	if err == nil {
		return false
	}
	var pg *pgconn.PgError
	if errors.As(err, &pg) {
		return pg.Code == "23505"
	}
	return strings.Contains(err.Error(), "UNIQUE constraint failed")
}

// ListTablesQuery lists the app's tables (one TEXT column, "name").
func ListTablesQuery(db *sql.DB) string {
	if IsPostgres(db) {
		return `SELECT table_name::text AS name FROM information_schema.tables
		        WHERE table_schema = current_schema() AND table_type = 'BASE TABLE' ORDER BY table_name`
	}
	return `SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name`
}

// TableInfoQuery returns columns shaped like SQLite's PRAGMA table_info:
// cid, name, type, notnull, dflt_value, pk.
func TableInfoQuery(db *sql.DB, table string) (string, []any) {
	if IsPostgres(db) {
		return `SELECT (c.ordinal_position - 1)::int AS cid, c.column_name::text AS name,
		        (CASE WHEN c.data_type = 'USER-DEFINED' THEN c.udt_name ELSE c.data_type END)::text AS type,
		        (CASE WHEN c.is_nullable = 'NO' THEN 1 ELSE 0 END)::int AS notnull,
		        c.column_default::text AS dflt_value,
		        (CASE WHEN EXISTS (
		            SELECT 1 FROM information_schema.table_constraints tc
		            JOIN information_schema.key_column_usage k
		              ON k.constraint_name = tc.constraint_name AND k.table_schema = tc.table_schema
		            WHERE tc.table_schema = c.table_schema AND tc.table_name = c.table_name
		              AND tc.constraint_type = 'PRIMARY KEY' AND k.column_name = c.column_name)
		         THEN 1 ELSE 0 END)::int AS pk
		        FROM information_schema.columns c
		        WHERE c.table_schema = current_schema() AND c.table_name = ?
		        ORDER BY c.ordinal_position`, []any{table}
	}
	return fmt.Sprintf(`PRAGMA table_info("%s")`, strings.ReplaceAll(table, `"`, `""`)), nil
}

// TableDDL returns a CREATE TABLE statement for the table (for SQL dumps).
func TableDDL(db *sql.DB, table string) string {
	if !IsPostgres(db) {
		var ddl string
		_ = db.QueryRow(`SELECT sql FROM sqlite_master WHERE type='table' AND name = ?`, table).Scan(&ddl)
		return ddl
	}
	q, args := TableInfoQuery(db, table)
	rows, err := db.Query(q, args...)
	if err != nil {
		return ""
	}
	defer rows.Close()
	var cols, pks []string
	for rows.Next() {
		var (
			cid, notNull, pk int
			name, typ        string
			dflt             sql.NullString
		)
		if rows.Scan(&cid, &name, &typ, &notNull, &dflt, &pk) != nil {
			continue
		}
		col := fmt.Sprintf(`  "%s" %s`, name, typ)
		if notNull == 1 {
			col += " NOT NULL"
		}
		if dflt.Valid && !strings.HasPrefix(dflt.String, "nextval") {
			col += " DEFAULT " + dflt.String
		}
		cols = append(cols, col)
		if pk == 1 {
			pks = append(pks, `"`+name+`"`)
		}
	}
	if len(pks) > 0 {
		cols = append(cols, "  PRIMARY KEY ("+strings.Join(pks, ", ")+")")
	}
	return fmt.Sprintf("CREATE TABLE \"%s\" (\n%s\n)", table, strings.Join(cols, ",\n"))
}

// ResetSequences moves every identity sequence past the highest id (after
// rows were inserted with explicit ids).
func ResetSequences(ctx context.Context, db *sql.DB) error {
	for _, t := range Tables {
		var hasID bool
		if err := db.QueryRowContext(ctx, `SELECT EXISTS (SELECT 1 FROM information_schema.columns
			WHERE table_schema = current_schema() AND table_name = ? AND column_name = 'id')`, t).Scan(&hasID); err != nil {
			return err
		}
		if !hasID {
			continue
		}
		q := fmt.Sprintf(`SELECT setval(pg_get_serial_sequence('%s', 'id'), COALESCE(MAX(id), 1), MAX(id) IS NOT NULL) FROM "%s"`, t, t)
		if _, err := db.ExecContext(ctx, q); err != nil {
			return fmt.Errorf("reset sequence %s: %w", t, err)
		}
	}
	return nil
}

// rebind turns "?" placeholders into $1, $2, … outside quoted text.
func rebind(q string) string {
	if !strings.Contains(q, "?") {
		return q
	}
	var b strings.Builder
	b.Grow(len(q) + 8)
	n := 0
	var quote byte
	for i := 0; i < len(q); i++ {
		c := q[i]
		switch {
		case quote != 0:
			if c == quote {
				quote = 0
			}
		case c == '\'' || c == '"':
			quote = c
		case c == '?':
			n++
			fmt.Fprintf(&b, "$%d", n)
			continue
		}
		b.WriteByte(c)
	}
	return b.String()
}

// rebindDriver wraps pgx's database/sql driver and rewrites placeholders.
type rebindDriver struct{ base driver.Driver }

func (d rebindDriver) Open(name string) (driver.Conn, error) {
	c, err := d.base.Open(name)
	if err != nil {
		return nil, err
	}
	return &rebindConn{c}, nil
}

type rebindConn struct{ driver.Conn }

func (c *rebindConn) Prepare(q string) (driver.Stmt, error) { return c.Conn.Prepare(rebind(q)) }

func (c *rebindConn) PrepareContext(ctx context.Context, q string) (driver.Stmt, error) {
	return c.Conn.(driver.ConnPrepareContext).PrepareContext(ctx, rebind(q))
}

func (c *rebindConn) ExecContext(ctx context.Context, q string, args []driver.NamedValue) (driver.Result, error) {
	return c.Conn.(driver.ExecerContext).ExecContext(ctx, rebind(q), args)
}

func (c *rebindConn) QueryContext(ctx context.Context, q string, args []driver.NamedValue) (driver.Rows, error) {
	return c.Conn.(driver.QueryerContext).QueryContext(ctx, rebind(q), args)
}

func (c *rebindConn) BeginTx(ctx context.Context, opts driver.TxOptions) (driver.Tx, error) {
	return c.Conn.(driver.ConnBeginTx).BeginTx(ctx, opts)
}

func (c *rebindConn) Ping(ctx context.Context) error {
	if p, ok := c.Conn.(driver.Pinger); ok {
		return p.Ping(ctx)
	}
	return nil
}

func (c *rebindConn) ResetSession(ctx context.Context) error {
	if r, ok := c.Conn.(driver.SessionResetter); ok {
		return r.ResetSession(ctx)
	}
	return nil
}

func (c *rebindConn) IsValid() bool {
	if v, ok := c.Conn.(driver.Validator); ok {
		return v.IsValid()
	}
	return true
}

func (c *rebindConn) CheckNamedValue(nv *driver.NamedValue) error {
	if ch, ok := c.Conn.(driver.NamedValueChecker); ok {
		return ch.CheckNamedValue(nv)
	}
	return driver.ErrSkip
}

// InsertID reads the id from an "INSERT … RETURNING id" row (both databases;
// Postgres's driver has no LastInsertId).
func InsertID(row *sql.Row) (int64, error) {
	var id int64
	err := row.Scan(&id)
	return id, err
}
