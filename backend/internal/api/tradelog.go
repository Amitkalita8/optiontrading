package api

import (
	"fmt"
	"net/http"
	"strings"

	"optiontrading/backend/internal/tradelog"
)

func (a *API) tradelogRoutes(mux *http.ServeMux) {
	mux.HandleFunc("GET /api/trade-log", a.listTradeLog)
	mux.HandleFunc("POST /api/trade-log", a.appendTradeLog)
	mux.HandleFunc("GET /api/trade-reports", a.listTradeReports)
	mux.HandleFunc("GET /api/trade-reports/{id}", a.getTradeReport)
	mux.HandleFunc("GET /api/trade-reports/{id}/download", a.downloadTradeReport)
}

func (a *API) listTradeLog(w http.ResponseWriter, r *http.Request) {
	list, err := a.tradeLog.List(r.Context(), a.userID(r))
	if err != nil {
		a.internalError(w, "list trade log", err)
		return
	}
	if list == nil {
		list = []tradelog.Entry{}
	}
	writeJSON(w, http.StatusOK, map[string]any{"entries": list})
}

func (a *API) appendTradeLog(w http.ResponseWriter, r *http.Request) {
	var in tradelog.Input
	if !decodeBody(w, r, &in) {
		return
	}
	e, err := a.tradeLog.Append(r.Context(), in, a.userID(r))
	if err != nil {
		a.internalError(w, "append trade log", err)
		return
	}
	writeJSON(w, http.StatusCreated, e)
}

func (a *API) listTradeReports(w http.ResponseWriter, r *http.Request) {
	reports := getDemoTradeReports()
	writeJSON(w, http.StatusOK, map[string]any{"reports": reports})
}

func (a *API) getTradeReport(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	reports := getDemoTradeReports()
	for _, rep := range reports {
		if strings.EqualFold(rep["id"].(string), id) || strings.EqualFold(rep["symbol"].(string), id) {
			writeJSON(w, http.StatusOK, rep)
			return
		}
	}
	writeJSON(w, http.StatusOK, reports[0])
}

func (a *API) downloadTradeReport(w http.ResponseWriter, r *http.Request) {
	id := r.PathValue("id")
	reports := getDemoTradeReports()
	target := reports[0]
	for _, rep := range reports {
		if strings.EqualFold(rep["id"].(string), id) || strings.EqualFold(rep["symbol"].(string), id) {
			target = rep
			break
		}
	}

	sym := target["symbol"].(string)
	content := fmt.Sprintf(
		"TRADE REPORT\n===============================\n"+
			"Symbol: %s (%s)\n"+
			"Strategy: %s\n"+
			"Detail: %s\n"+
			"Net P/L: %s\n"+
			"R-Multiple: %s\n"+
			"Trade Duration: %s\n"+
			"Entry Price: %s\n"+
			"Exit Price: %s\n"+
			"Lot Size: %s\n"+
			"Result: %s\n\n"+
			"Risk Assessment:\n"+
			"- Planned Risk: $1,000 (1.00%%)\n"+
			"- Actual Risk: $980 (0.98%%)\n"+
			"- Planned Reward: $1,600 (1.60%%)\n"+
			"- Actual Reward: $1,320 (1.32%%)\n\n"+
			"Generated by Option Trading Platform\n",
		sym, target["companyName"], target["strategy"], target["tradeDetail"],
		target["plFormatted"], target["rMultiple"], target["duration"],
		target["entryPrice"], target["exitPrice"], target["lotSize"], target["result"],
	)

	w.Header().Set("Content-Type", "text/plain; charset=utf-8")
	w.Header().Set("Content-Disposition", fmt.Sprintf("attachment; filename=\"Trade_Report_%s.txt\"", sym))
	w.WriteHeader(http.StatusOK)
	_, _ = w.Write([]byte(content))
}

