export function getExistingPosition(idOrSymbol) {
  if (!idOrSymbol) return existingPositions[0];
  const query = idOrSymbol.toLowerCase();
  return (
    existingPositions.find(
      (p) => p.id.toLowerCase() === query || p.symbol.toLowerCase() === query
    ) || existingPositions[0]
  );
}
